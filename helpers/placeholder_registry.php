/**
 * Compile a list of available placeholders for the template designer UI
 * grouped by category
 */
function getGroupedPlaceholders(?string $type = null): array {
    $groups = [
        'system' => [
            'label' => 'System Fields',
            'placeholders' => getDefaultPlaceholders(),
        ],
    ];

    if ($type) {
        $module = getModulePlaceholders($type);
        if (!empty($module)) {
            $groups['module'] = [
                'label' => 'Module Fields (' . ucwords(str_replace('_', ' ', $type)) . ')',
                'placeholders' => $module,
            ];
        }
    }

    return $groups;
}

